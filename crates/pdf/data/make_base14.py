"""Write ``src/base14.rs``: the 14 standard fonts' glyph widths by Unicode, and their ascent and descent.

The widths are PyMuPDF's URW fonts', which are metric-compatible with Adobe's (Helvetica ``A`` 667, Times-Roman
722, Times-Italic 611, Courier 600). The ascent and descent are the Adobe AFM values (``Ascender``/``Descender``;
``FontBBox`` for Symbol and ZapfDingbats, which state neither). Run from ``crates/pdf``:
``python data/make_base14.py``.
"""

from pathlib import Path

import pymupdf

#: (standard name, PyMuPDF's name for its metric-compatible font, ascent, descent) -- in thousandths of the size.
FONTS = (
    ('Helvetica', 'helv', 718, -207),
    ('Helvetica-Oblique', 'heit', 718, -207),
    ('Helvetica-Bold', 'hebo', 718, -207),
    ('Helvetica-BoldOblique', 'hebi', 718, -207),
    ('Times-Roman', 'tiro', 683, -217),
    ('Times-Italic', 'tiit', 683, -217),
    ('Times-Bold', 'tibo', 683, -217),
    ('Times-BoldItalic', 'tibi', 683, -217),
    ('Courier', 'cour', 629, -157),
    ('Courier-Oblique', 'coit', 629, -157),
    ('Courier-Bold', 'cobo', 629, -157),
    ('Courier-BoldOblique', 'cobi', 629, -157),
    ('Symbol', 'symb', 1010, -293),
    ('ZapfDingbats', 'zadb', 820, -143),
)


def entry(name: str, short: str, ascent: int, descent: int) -> str:
    """One font's ``Metrics`` literal."""
    font = pymupdf.Font(short)
    widths = [(c, round(font.glyph_advance(c) * 1000)) for c in range(0x20, 0x2800) if font.has_glyph(c)]
    rows = ',\n'.join(f'            ({c:#06x}, {w})' for c, w in widths)
    return (
        f'    Metrics {{\n        name: "{name}",\n        ascent: {ascent}.0,\n        descent: {descent}.0,\n'
        f'        widths: &[\n{rows},\n        ],\n    }}'
    )


if __name__ == '__main__':
    body = ',\n'.join(entry(*f) for f in FONTS)
    out = (
        "//! The 14 standard fonts' metrics. GENERATED by `data/make_base14.py`; edit that, not this.\n\n"
        '/// One standard font: its name, ascent and descent, and its widths by Unicode (thousandths of the size).\n'
        '#[derive(Debug)]\n'
        "pub struct Metrics {\n    /// The standard name.\n    pub name: &'static str,\n"
        '    /// The ascent.\n    pub ascent: f64,\n    /// The descent (negative).\n    pub descent: f64,\n'
        "    /// (Unicode scalar, width), sorted by Unicode.\n    pub widths: &'static [(u32, u16)],\n}\n\n"
        f'/// Every standard font.\npub static FONTS: [Metrics; 14] = [\n{body},\n];\n'
    )
    Path(__file__).parent.parent.joinpath('src', 'base14.rs').write_text(out, encoding='utf-8', newline='\n')
