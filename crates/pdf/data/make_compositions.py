"""Write ``src/compositions.rs``: the NFC composition of each letter with each accent ``accents.rs`` composes.

For every Unicode letter (general category ``L*``) in NFC and every combining mark of :data:`MARKS`, the pair is kept
when its NFC form is not the pair itself (``u`` and U+0308 are ``ü``; ``ü`` and U+0301 are ``ǘ``); a pair not kept
is its own NFC form. The Unicode version is this Python's ``unicodedata``'s. Run from ``crates/pdf``:
``python data/make_compositions.py``.
"""

import sys
import unicodedata
from pathlib import Path

#: The combining marks of the spacing accents ``accents.rs`` reads: grave, acute, circumflex, tilde, macron, breve,
#: dot above, diaeresis, ring above, double acute, caron, cedilla, ogonek.
MARKS = (0x300, 0x301, 0x302, 0x303, 0x304, 0x306, 0x307, 0x308, 0x30A, 0x30B, 0x30C, 0x327, 0x328)


def pairs() -> list[tuple[int, int, str]]:
    """(letter, mark, NFC of the two) for every pair whose NFC form is not the pair, sorted."""
    out = []
    for letter in range(sys.maxunicode + 1):
        if not unicodedata.category(chr(letter)).startswith('L') or not unicodedata.is_normalized('NFC', chr(letter)):
            continue
        for mark in MARKS:
            pair = chr(letter) + chr(mark)
            composed = unicodedata.normalize('NFC', pair)
            if composed != pair:
                out.append((letter, mark, composed))
    return out


def literal(text: str) -> str:
    """``text`` as a Rust string literal of escapes."""
    return '"' + ''.join(f'\\u{{{ord(c):X}}}' for c in text) + '"'


if __name__ == '__main__':
    found = pairs()
    rows = '\n'.join(f"    ('\\u{{{a:X}}}', '\\u{{{m:X}}}', {literal(c)})," for a, m, c in found)
    out = (
        '//! The NFC composition of a letter with a combining accent, where it is not the pair itself.\n'
        '//! GENERATED by `data/make_compositions.py` (Unicode '
        f'{unicodedata.unidata_version}); edit that, not this.\n\n'
        '/// (letter, combining mark, their NFC form), sorted by letter, then mark.\n'
        f'pub(crate) static COMPOSED: [(char, char, &str); {len(found)}] = [\n{rows}\n];\n'
    )
    Path(__file__).parent.parent.joinpath('src', 'compositions.rs').write_text(out, encoding='utf-8', newline='\n')
